#!/usr/bin/env node
/**
 * Regenerates src/demoSnapshot.js from a running backend.
 *
 * The hosted browser build has no backend, so it serves this snapshot instead.
 * Capturing it from the real API rather than hand-writing it is the point: the
 * fixture cannot drift away from the response shapes the UI actually parses.
 *
 *   npm run backend:dev                     # in one shell
 *   node scripts/capture-demo-snapshot.mjs  # in another
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const BASE = process.env.BEHAVIOR_URL || "http://127.0.0.1:8765";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

async function get(pathname) {
  const response = await fetch(BASE + pathname);
  if (!response.ok) throw new Error(`GET ${pathname} -> ${response.status}`);
  return response.json();
}

async function post(pathname, body) {
  const response = await fetch(BASE + pathname, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body ?? {}),
  });
  if (!response.ok) throw new Error(`POST ${pathname} -> ${response.status}`);
  return response.json();
}

const sessions = await get("/api/sessions?limit=30");
if (!sessions.length) throw new Error("No sessions on the backend — seed one before capturing.");
const sessionId = sessions[0].id;

const workflows = await get("/api/workflows");
if (!workflows.length) throw new Error("No detected workflows — drive a repeated sequence first.");

const snapshot = {
  status: await get("/api/system/status"),
  session: sessions[0],
  metrics: await get(`/api/metrics/current?session_id=${sessionId}`),
  metricHistory: await get(`/api/metrics/history?limit=60&session_id=${sessionId}`),
  rhythm: await get(`/api/metrics/rhythm?points=36&session_id=${sessionId}`),
  sessions,
  workflows,
  recommendations: await get("/api/recommendations"),
  privacy: await get("/api/privacy"),
  plan: await post(`/api/automation/${workflows[0].id}/plan`, {}),
  assistant: await post("/api/assistant/ask", { question: "What am I repeating?" }),
  briefing: await post("/api/voice/briefing", { length: "standard" }),
};

/**
 * AGENTS.md asks for prototype data to be labelled illustrative. Relabel every
 * record that carries a data_origin, so nothing in the hosted preview can be
 * read as observed behaviour — including by the dashboard's own Source readout.
 */
function relabel(value) {
  if (Array.isArray(value)) return value.map(relabel);
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, inner]) =>
        key === "data_origin" ? [key, "illustrative_preview"] : [key, relabel(inner)],
      ),
    );
  }
  return value;
}

const labelled = relabel(snapshot);

const header = `// GENERATED by scripts/capture-demo-snapshot.mjs — do not edit by hand.
//
// A real capture from the local backend, served by the hosted browser build so a
// visitor sees the interface populated instead of "Backend reconnecting". Every
// record is relabelled data_origin: "illustrative_preview" on the way in, so
// nothing here can be mistaken for observed behaviour.

`;

writeFileSync(
  path.join(root, "src", "demoSnapshot.js"),
  header + "export const DEMO_SNAPSHOT = " + JSON.stringify(labelled, null, 2) + ";\n",
  "utf8",
);

console.log("Wrote src/demoSnapshot.js from " + BASE);
